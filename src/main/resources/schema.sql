-- ========================================================================
-- F4：结算单状态机（结算单/明细/流转日志/迁移规则配置）。
-- 结算单从已完工未结算作业单生成，金额 = 轨迹核算面积 × 单价（生成时快照，不再二次加工）；
-- 状态迁移规则落库可配，所有变更走统一入口校验，非法迁移即拒绝；
-- 每次变更带版本与操作人，流转历史只追加不修改。
-- ========================================================================

-- 旧库升级：t_work_order 补结算占用标记（新库建表已含此列，此处幂等）；
-- 索引必须放在 ALTER 之后：旧库此时才有 settle_id 列
ALTER TABLE t_work_order ADD COLUMN IF NOT EXISTS settle_id BIGINT;
CREATE INDEX IF NOT EXISTS idx_work_order_settle ON t_work_order (settle_id);

-- 结算单：一台农机一段时间内已完工作业单的汇总结算
CREATE TABLE IF NOT EXISTS t_settle_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    settle_no VARCHAR(40) NOT NULL,
    machine_id BIGINT NOT NULL,
    machine_code VARCHAR(40),
    machine_name VARCHAR(80),
    period_start DATE,
    period_end DATE,
    order_count INT NOT NULL DEFAULT 0,
    total_area DECIMAL(14, 2) NOT NULL DEFAULT 0,
    unit_price DECIMAL(12, 2) NOT NULL,
    total_amount DECIMAL(14, 2) NOT NULL DEFAULT 0,
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    remark VARCHAR(255),
    request_no VARCHAR(64) NOT NULL,
    version INT NOT NULL DEFAULT 0,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_settle_order_no UNIQUE (settle_no),
    CONSTRAINT uk_settle_order_request_no UNIQUE (request_no)
);
CREATE INDEX IF NOT EXISTS idx_settle_order_machine ON t_settle_order (machine_id);
CREATE INDEX IF NOT EXISTS idx_settle_order_status ON t_settle_order (status);

-- 结算明细：逐单快照作业单号/权威面积/单价/金额；历史保留，作废不删行
CREATE TABLE IF NOT EXISTS t_settle_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    settle_id BIGINT NOT NULL,
    work_order_id BIGINT NOT NULL,
    order_no VARCHAR(40) NOT NULL,
    operation_type VARCHAR(40),
    track_area DECIMAL(12, 2) NOT NULL,
    unit_price DECIMAL(12, 2) NOT NULL,
    amount DECIMAL(14, 2) NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_settle_item_settle ON t_settle_item (settle_id);
CREATE INDEX IF NOT EXISTS idx_settle_item_order ON t_settle_item (work_order_id);

-- 结算状态流转日志：只追加、不修改；每次变更带前后状态、前后版本、操作人、请求号
CREATE TABLE IF NOT EXISTS t_settle_status_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    settle_id BIGINT NOT NULL,
    settle_no VARCHAR(40) NOT NULL,
    from_status VARCHAR(16),
    to_status VARCHAR(16) NOT NULL,
    from_version INT,
    to_version INT,
    operator VARCHAR(64) NOT NULL,
    request_no VARCHAR(64),
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_settle_status_log_settle ON t_settle_status_log (settle_id);

-- 状态迁移规则（配置化）：enabled=1 才放行；在线启停走请求号台账，规则行带乐观锁
CREATE TABLE IF NOT EXISTS t_settle_transition_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_status VARCHAR(16) NOT NULL,
    to_status VARCHAR(16) NOT NULL,
    enabled CHAR(1) NOT NULL DEFAULT '1',
    remark VARCHAR(255),
    version INT NOT NULL DEFAULT 0,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_settle_transition UNIQUE (from_status, to_status)
);

MERGE INTO t_settle_transition_rule (from_status, to_status, enabled, remark)
KEY (from_status, to_status)
VALUES ('DRAFT', 'CONFIRMED', '1', '草稿确认：金额与明细核对无误');
MERGE INTO t_settle_transition_rule (from_status, to_status, enabled, remark)
KEY (from_status, to_status)
VALUES ('DRAFT', 'VOID', '1', '草稿作废：释放作业单，可重新结算');
MERGE INTO t_settle_transition_rule (from_status, to_status, enabled, remark)
KEY (from_status, to_status)
VALUES ('CONFIRMED', 'PAID', '1', '确认后付款：终态');
MERGE INTO t_settle_transition_rule (from_status, to_status, enabled, remark)
KEY (from_status, to_status)
VALUES ('CONFIRMED', 'VOID', '1', '确认后作废：释放作业单，可重新结算');

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('f4-settlement', '结算单状态机（结算生成/迁移规则配置化/统一入口校验/版本与操作人/流转历史）');
