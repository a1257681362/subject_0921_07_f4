-- H2 本地文件数据库初始化脚本。
-- F1：农机底账 + 作业单主链路（建档/状态流转/轨迹面积/红冲）。
-- 约定：历史数据不物理删除，停用/红冲只改状态；所有写请求凭请求号登记 t_request_record。
CREATE TABLE IF NOT EXISTS t_evops_schema_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(32) NOT NULL,
    description VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_evops_schema_version UNIQUE (version_no)
);

-- 农机基础信息
CREATE TABLE IF NOT EXISTS t_machine (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_code VARCHAR(40) NOT NULL,
    machine_name VARCHAR(80) NOT NULL,
    machine_type VARCHAR(40),
    plate_no VARCHAR(40),
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    remark VARCHAR(255),
    version INT NOT NULL DEFAULT 0,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_machine_code UNIQUE (machine_code)
);

-- 作业单（track_area 为轨迹核算的权威面积，manual_area 仅人工上报参考）
CREATE TABLE IF NOT EXISTS t_work_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no VARCHAR(40) NOT NULL,
    machine_id BIGINT NOT NULL,
    operation_type VARCHAR(40) NOT NULL,
    plot_name VARCHAR(80),
    track_area DECIMAL(12, 2),
    track_time TIMESTAMP,
    manual_area DECIMAL(12, 2),
    manual_reporter VARCHAR(64),
    manual_report_time TIMESTAMP,
    status VARCHAR(16) NOT NULL DEFAULT 'CREATED',
    reversal_flag CHAR(1) NOT NULL DEFAULT '0',
    origin_order_id BIGINT,
    -- 结算占用标记：生成结算单时写入 t_settle_order.id，结算单作废时释放（置 NULL）
    settle_id BIGINT,
    remark VARCHAR(255),
    version INT NOT NULL DEFAULT 0,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_work_order_no UNIQUE (order_no)
);
CREATE INDEX IF NOT EXISTS idx_work_order_machine ON t_work_order (machine_id);

-- 作业单状态流转日志
CREATE TABLE IF NOT EXISTS t_work_order_status_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    order_no VARCHAR(40) NOT NULL,
    from_status VARCHAR(16),
    to_status VARCHAR(16) NOT NULL,
    request_no VARCHAR(64),
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_status_log_order ON t_work_order_status_log (order_id);

-- 请求号台账：新增/变更请求必须携带请求号，全局唯一，防重放
CREATE TABLE IF NOT EXISTS t_request_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_no VARCHAR(64) NOT NULL,
    biz_type VARCHAR(32) NOT NULL,
    biz_key VARCHAR(64),
    create_by BIGINT,
    create_time TIMESTAMP,
    CONSTRAINT uk_request_no UNIQUE (request_no)
);

-- 卫星轨迹核算平台账单（对方账）。reversal_flag=1 为红冲账单，reverses_bill_id 指向被红冲账单。
CREATE TABLE IF NOT EXISTS t_satellite_bill (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_no VARCHAR(40) NOT NULL,
    order_no VARCHAR(40) NOT NULL,
    machine_id BIGINT,
    track_area DECIMAL(12, 2) NOT NULL,
    bill_time TIMESTAMP NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    reversal_flag CHAR(1) NOT NULL DEFAULT '0',
    reverses_bill_id BIGINT,
    remark VARCHAR(255),
    version INT NOT NULL DEFAULT 0,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_satellite_bill_no UNIQUE (bill_no)
);
CREATE INDEX IF NOT EXISTS idx_satellite_bill_order ON t_satellite_bill (order_no);

-- 勾稽批次：一次定时/手工勾稽一行。eng 列为新引擎口径快照，leg_ 列为并跑期旧引擎口径。
CREATE TABLE IF NOT EXISTS t_recon_batch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_no VARCHAR(40) NOT NULL,
    reconcile_date DATE NOT NULL,
    triggered_by VARCHAR(16) NOT NULL,
    engine_mode VARCHAR(16) NOT NULL,
    tolerance DECIMAL(12, 2),
    status VARCHAR(16) NOT NULL,
    eng_matched_count INT NOT NULL DEFAULT 0,
    eng_local_only_count INT NOT NULL DEFAULT 0,
    eng_remote_only_count INT NOT NULL DEFAULT 0,
    eng_amount_diff_count INT NOT NULL DEFAULT 0,
    eng_diff_count INT NOT NULL DEFAULT 0,
    eng_resolved_diff_count INT NOT NULL DEFAULT 0,
    eng_open_diff_count INT NOT NULL DEFAULT 0,
    eng_local_total DECIMAL(14, 2) NOT NULL DEFAULT 0,
    eng_remote_total DECIMAL(14, 2) NOT NULL DEFAULT 0,
    eng_diff_total DECIMAL(14, 2) NOT NULL DEFAULT 0,
    leg_matched_count INT,
    leg_diff_count INT,
    leg_open_diff_count INT,
    leg_local_total DECIMAL(14, 2),
    leg_remote_total DECIMAL(14, 2),
    leg_diff_total DECIMAL(14, 2),
    engine_compare_result VARCHAR(16),
    engine_compare_detail VARCHAR(1000),
    started_at TIMESTAMP,
    finished_at TIMESTAMP,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_recon_batch_no UNIQUE (batch_no),
    CONSTRAINT uk_recon_batch_date UNIQUE (reconcile_date)
);

-- 勾稽差异明细：一笔对一笔，双方明细落库；核销后差异即时清零，记录保留不物理删除。
CREATE TABLE IF NOT EXISTS t_recon_detail (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    reconcile_date DATE NOT NULL,
    engine VARCHAR(8) NOT NULL,
    diff_type VARCHAR(20) NOT NULL,
    order_no VARCHAR(40),
    local_id BIGINT,
    local_order_no VARCHAR(40),
    local_track_area DECIMAL(12, 2),
    local_track_time TIMESTAMP,
    local_status VARCHAR(16),
    local_reversal_flag CHAR(1),
    remote_id BIGINT,
    remote_bill_no VARCHAR(40),
    remote_order_no VARCHAR(40),
    remote_track_area DECIMAL(12, 2),
    remote_bill_time TIMESTAMP,
    remote_status VARCHAR(16),
    remote_reversal_flag CHAR(1),
    diff_area DECIMAL(14, 2) NOT NULL DEFAULT 0,
    abs_diff_area DECIMAL(14, 2) NOT NULL DEFAULT 0,
    status VARCHAR(16) NOT NULL DEFAULT 'OPEN',
    carried_from_detail_id BIGINT,
    writeoff_id BIGINT,
    writeoff_time TIMESTAMP,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_recon_detail_batch ON t_recon_detail (batch_id);
CREATE INDEX IF NOT EXISTS idx_recon_detail_status ON t_recon_detail (status);
CREATE INDEX IF NOT EXISTS idx_recon_detail_date ON t_recon_detail (reconcile_date);

-- 核销（手工调整）台账：申请→审批/驳回；审批与差异清零同一事务。
CREATE TABLE IF NOT EXISTS t_recon_writeoff (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    writeoff_no VARCHAR(40) NOT NULL,
    detail_id BIGINT,
    reconcile_date DATE NOT NULL,
    order_no VARCHAR(40),
    diff_type VARCHAR(20) NOT NULL,
    adjust_type VARCHAR(20) NOT NULL,
    diff_area DECIMAL(14, 2) NOT NULL,
    local_side_snapshot VARCHAR(500),
    remote_side_snapshot VARCHAR(500),
    reason VARCHAR(255) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'APPLIED',
    approver VARCHAR(64),
    approve_time TIMESTAMP,
    approve_remark VARCHAR(255),
    reject_reason VARCHAR(255),
    request_no VARCHAR(64) NOT NULL,
    version INT NOT NULL DEFAULT 0,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_recon_writeoff_no UNIQUE (writeoff_no),
    CONSTRAINT uk_recon_writeoff_request_no UNIQUE (request_no)
);
CREATE INDEX IF NOT EXISTS idx_recon_writeoff_detail ON t_recon_writeoff (detail_id);

-- 勾稽运行期配置（覆盖 application.yml 默认值）：TOLERANCE 匹配容差、ENGINE_MODE 引擎模式
CREATE TABLE IF NOT EXISTS t_recon_config (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    config_key VARCHAR(40) NOT NULL,
    config_value VARCHAR(120) NOT NULL,
    version INT NOT NULL DEFAULT 0,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_recon_config_key UNIQUE (config_key)
);

